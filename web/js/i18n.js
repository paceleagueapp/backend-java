// 서버가 보낸 영어 오류 메시지 → 현재 언어 문장. 모르는 메시지는 원문 그대로.
function localizeServerMessage(message) {
  if (!message) return message;
  var key = SERVER_ERROR_KEYS[message];
  var vars = {};
  if (!key) {
    for (var i = 0; i < SERVER_ERROR_PATTERNS.length; i++) {
      var m = message.match(SERVER_ERROR_PATTERNS[i][0]);
      if (m) {
        key = SERVER_ERROR_PATTERNS[i][1];
        SERVER_ERROR_PATTERNS[i][2].forEach(function (name, idx) { vars[name] = m[idx + 1]; });
        break;
      }
    }
  }
  if (!key) return message;
  var text = t(key);
  if (text === key) return message;
  return text.replace(/\{(\w+)\}/g, function (_, name) { return vars[name] != null ? vars[name] : ''; });
}

function getLang() {
  var stored = localStorage.getItem('pl_lang');
  if (stored && TRANSLATIONS[stored]) return stored;
  var nav = ((navigator.language || 'ko').split('-')[0]).toLowerCase();
  return TRANSLATIONS[nav] ? nav : 'ko';
}

function setLang(code) {
  localStorage.setItem('pl_lang', code);
}

function t(key) {
  var lang = getLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.ko[key] || key;
}

function renderLangSelect(selectEl) {
  selectEl.innerHTML = SUPPORTED_LANGUAGES.map(function (l) {
    return '<option value="' + l.code + '">' + l.flag + ' ' + l.name + '</option>';
  }).join('');
  selectEl.value = getLang();
  selectEl.addEventListener('change', function () {
    setLang(selectEl.value);
    window.location.reload();
  });
}

// 상단 "소개"/"가이드" 메뉴는 선택 언어의 페이지로 (/about·/guide = 한국어, /{lang}/about·/{lang}/guide = 그 외 9개 언어)
function localizedPath(path) {
  var lang = getLang();
  return lang === 'ko' ? path : '/' + lang + path;
}
document.querySelectorAll('a[data-navkey="navGuide"]').forEach(function (a) {
  a.setAttribute('href', localizedPath('/guide'));
});
document.querySelectorAll('a[data-navkey="navAbout"]').forEach(function (a) {
  a.setAttribute('href', localizedPath('/about'));
});
